@app.route("/trade/<int:trade_id>/delete", methods=["POST"])
@login_required
def delete_trade(trade_id):
    user_id = current_user()["id"]

    with get_db() as conn:
        trade = conn.execute(
            """
            SELECT screenshot_4h, screenshot_15m, screenshot_5m
            FROM trades
            WHERE id = %s AND user_id = %s
            """,
            (trade_id, user_id),
        ).fetchone()

        if trade:
            conn.execute(
                "DELETE FROM trades WHERE id = %s AND user_id = %s",
                (trade_id, user_id),
            )

    if trade:
        for path in (
            trade["screenshot_4h"],
            trade["screenshot_15m"],
            trade["screenshot_5m"],
        ):
            if path:
                safe_path = (BASE_DIR / "static" / path).resolve()

                if safe_path.is_relative_to(UPLOAD_DIR.resolve()):
                    safe_path.unlink(missing_ok=True)

        flash("Trade deleted.", "success")
    else:
        flash("Trade not found.", "error")

    return redirect(url_for("index"))


