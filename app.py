@app.route("/export/csv")
@login_required
def export_csv():
    fields, rows = export_rows(current_user()["id"])

    output = io.StringIO()
    writer = csv.DictWriter(output, fieldnames=fields)

    writer.writeheader()

    for row in rows:
        row["rules_followed"] = (
            "Yes" if row["rules_followed"] else "No"
        )

        writer.writerow({
            field: row.get(field, "")
            for field in fields
        })

    response = app.response_class(
        output.getvalue(),
        mimetype="text/csv",
    )

    response.headers["Content-Disposition"] = (
        "attachment; filename=tradelog-journal.csv"
    )

    return response


