@app.route("/trade", methods=["POST"])
@login_required
def add_trade():
    form = request.form
    saved_screenshots = []

    try:
        trade_date = form["trade_date"].replace("T", " ")
        user_id = current_user()["id"]

        symbol = form["symbol"].strip().upper()
        direction = form["direction"]
        setup = form["setup"]
        market_condition = form["market_condition"]
        exit_reason = form["exit_reason"]

        if not symbol or not setup or not market_condition or not exit_reason:
            raise ValueError("Complete all required trade fields.")

        if direction not in ("Long", "Short"):
            raise ValueError("Direction must be Long or Short.")

        planned_rr = float(form.get("planned_rr") or 0)
        realised_rr = float(form.get("realised_rr") or 0)
        entry_price = float(form.get("entry_price") or 0)
        exit_price = float(form.get("exit_price") or 0)
        quantity = float(form.get("quantity") or 0)
        pnl = float(form.get("pnl") or 0)

        with get_db() as conn:
            cursor = conn.execute(
                """
                INSERT INTO trades (
                    user_id, trade_date, symbol, direction, setup,
                    criteria_met, market_condition, planned_rr,
                    realised_rr, rules_followed, exit_reason,
                    entry_price, exit_price, quantity, pnl,
                    notes, created_at
                )
                VALUES (
                    %s, %s, %s, %s, %s, %s, %s, %s, %s,
                    %s, %s, %s, %s, %s, %s, %s, %s
                )
                RETURNING id
                """,
                (
                    user_id,
                    trade_date,
                    symbol,
                    direction,
                    setup,
                    form.get("criteria_met", ""),
                    market_condition,
                    planned_rr,
                    realised_rr,
                    1 if form.get("rules_followed") == "yes" else 0,
                    exit_reason,
                    entry_price,
                    exit_price,
                    quantity,
                    pnl,
                    form.get("notes", ""),
                    datetime.now(timezone.utc).isoformat(timespec="seconds"),
                ),
            )

            trade_id = cursor.fetchone()["id"]

            screenshot_paths = []

            for field, timeframe in (
                ("screenshot_4h", "4h"),
                ("screenshot_15m", "15m"),
                ("screenshot_5m", "5m"),
            ):
                path = save_screenshot(
                    request.files.get(field),
                    user_id,
                    trade_id,
                    timeframe,
                )

                screenshot_paths.append(path)

                if path:
                    saved_screenshots.append(UPLOAD_DIR / Path(path).name)

            conn.execute(
                """
                UPDATE trades
                SET screenshot_4h = %s,
                    screenshot_15m = %s,
                    screenshot_5m = %s
                WHERE id = %s AND user_id = %s
                """,
                (*screenshot_paths, trade_id, user_id),
            )

        flash("Trade logged successfully.", "success")

    except (KeyError, ValueError) as exc:
        # Remove any screenshots saved if this trade was rejected.
        for path in saved_screenshots:
            path.unlink(missing_ok=True)

        flash(f"Please check the required fields: {exc}", "error")

    except psycopg.Error:
        for path in saved_screenshots:
            path.unlink(missing_ok=True)

        app.logger.exception("Could not save trade to PostgreSQL.")
        flash(
            "The trade could not be saved. Please try again.",
            "error",
        )

    return redirect(url_for("index"))


