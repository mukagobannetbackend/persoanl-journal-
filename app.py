def init_db():
    with get_db() as conn:
        conn.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                initial_balance DOUBLE PRECISION NOT NULL DEFAULT 0,
                created_at TEXT NOT NULL
            )
        """)

        conn.execute("""
            CREATE TABLE IF NOT EXISTS trades (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
                trade_date TEXT NOT NULL,
                symbol TEXT NOT NULL,
                direction TEXT NOT NULL
                    CHECK (direction IN ('Long', 'Short')),
                setup TEXT NOT NULL,
                criteria_met TEXT,
                market_condition TEXT NOT NULL,
                planned_rr DOUBLE PRECISION NOT NULL DEFAULT 0,
                realised_rr DOUBLE PRECISION NOT NULL DEFAULT 0,
                rules_followed INTEGER NOT NULL DEFAULT 0,
                exit_reason TEXT NOT NULL,
                entry_price DOUBLE PRECISION,
                exit_price DOUBLE PRECISION,
                quantity DOUBLE PRECISION,
                pnl DOUBLE PRECISION NOT NULL DEFAULT 0,
                notes TEXT,
                screenshot_4h TEXT,
                screenshot_15m TEXT,
                screenshot_5m TEXT,
                created_at TEXT NOT NULL
            )
        """)

        # Support databases created.
        conn.execute("""
            ALTER TABLE users
            ADD COLUMN IF NOT EXISTS initial_balance
            DOUBLE PRECISION NOT NULL DEFAULT 0
        """)

        conn.execute("""
            ALTER TABLE trades
            ADD COLUMN IF NOT EXISTS user_id BIGINT
            REFERENCES users(id) ON DELETE CASCADE
        """)

        for column in (
            "screenshot_4h",
            "screenshot_15m",
            "screenshot_5m",
        ):
            conn.execute(
                f"ALTER TABLE trades ADD COLUMN IF NOT EXISTS {column} TEXT"
            )


