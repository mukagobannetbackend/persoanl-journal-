def build_analytics(trades, initial_balance=0):
    trades = [dict(row) for row in trades]

    pnl_total = sum(t["pnl"] for t in trades)
    wins = [t for t in trades if t["pnl"] > 0]
    losses = [t for t in trades if t["pnl"] < 0]

    rules_yes = [t for t in trades if t["rules_followed"]]
    rules_no = [t for t in trades if not t["rules_followed"]]

    def summary(items):
        pnl = sum(t["pnl"] for t in items)

        return {
            "count": len(items),
            "pnl": round(pnl, 2),
            "win_rate": round(
                (
                    sum(1 for t in items if t["pnl"] > 0)
                    / len(items) * 100
                ) if items else 0,
                1,
            ),
        }

    def counts(items, field):
        result = {}

        for item in items:
            value = item.get(field) or "Not specified"
            result[value] = result.get(value, 0) + 1

        return sorted(
            [
                {"label": key, "count": value}
                for key, value in result.items()
            ],
            key=lambda item: (-item["count"], item["label"]),
        )

    running = initial_balance
    equity = [
        {
            "date": "Starting balance",
            "value": round(initial_balance, 2),
        }
    ]

    for trade in sorted(
        trades,
        key=lambda item: (item["trade_date"], item["id"]),
    ):
        running += trade["pnl"]

        equity.append({
            "date": trade["trade_date"][:10],
            "value": round(running, 2),
        })

    mistakes = {
        "rule_breaks": len(rules_no),
        "rule_break_loss": round(
            sum(t["pnl"] for t in rules_no if t["pnl"] < 0), 2
        ),
        "manual_close_breaks": sum(
            1 for t in rules_no if t["exit_reason"] == "Manual close"
        ),
        "early_exit_breaks": sum(
            1 for t in rules_no
            if t["exit_reason"] in ("Manual close", "Breakeven")
        ),
        "top_setups": counts(rules_no, "setup")[:3],
        "top_conditions": counts(rules_no, "market_condition")[:3],
        "top_exit_reasons": counts(rules_no, "exit_reason")[:3],
    }

    return {
        "trades": trades,
        "initial_balance": round(initial_balance, 2),
        "current_equity": round(initial_balance + pnl_total, 2),
        "total_pnl": round(pnl_total, 2),
        "trade_count": len(trades),
        "win_rate": round(
            len(wins) / len(trades) * 100 if trades else 0,
            1,
        ),
        "avg_rr": round(
            sum(t["realised_rr"] for t in trades) / len(trades), 2
        ) if trades else 0,
        "avg_win": round(
            sum(t["pnl"] for t in wins) / len(wins), 2
        ) if wins else 0,
        "avg_loss": round(
            sum(t["pnl"] for t in losses) / len(losses), 2
        ) if losses else 0,
        "rules_yes": summary(rules_yes),
        "rules_no": summary(rules_no),
        "mistakes": mistakes,
        "equity": equity,
    }


