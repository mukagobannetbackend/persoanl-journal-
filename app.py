def current_user():
    user_id = session.get("user_id")

    if not user_id:
        return None

    with get_db() as conn:
        return conn.execute(
            """
            SELECT id, name, email, initial_balance
            FROM users
            WHERE id = %s
            """,
            (user_id,),
        ).fetchone()


def login_required(view):
    @wraps(view)
    def wrapped(*args, **kwargs):
        if not current_user():
            return redirect(url_for("login", next=request.path))

        return view(*args, **kwargs)

    return wrapped


# Only permit known sorting expressions in SQL.
TRADE_ORDER_OPTIONS = {
    "trade_date DESC, id DESC",
    "trade_date ASC, id ASC",
}


def get_user_trades(user_id, order="trade_date DESC, id DESC"):
    if order not in TRADE_ORDER_OPTIONS:
        order = "trade_date DESC, id DESC"

    with get_db() as conn:
        return conn.execute(
            f"""
            SELECT *
            FROM trades
            WHERE user_id = %s
            ORDER BY {order}
            """,
            (user_id,),
        ).fetchall()


