@app.route("/export/pdf")
@login_required
def export_pdf():
    from xml.sax.saxutils import escape

    from reportlab.lib import colors
    from reportlab.lib.pagesizes import landscape, letter
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.lib.units import inch
    from reportlab.platypus import (
        SimpleDocTemplate, Table, TableStyle,
        Paragraph, Spacer,
    )

    user = current_user()
    fields, rows = export_rows(user["id"])

    analytics_data = build_analytics(
        get_user_trades(user["id"], "trade_date ASC, id ASC"),
        user["initial_balance"],
    )

    buffer = io.BytesIO()

    doc = SimpleDocTemplate(
        buffer,
        pagesize=landscape(letter),
        rightMargin=0.35 * inch,
        leftMargin=0.35 * inch,
        topMargin=0.35 * inch,
        bottomMargin=0.35 * inch,
    )

    styles = getSampleStyleSheet()

    story = [
        Paragraph("TradeLog Pro — Trade Journal", styles["Title"]),
        Paragraph(
            (
                f"{escape(user['name'])} · "
                f"{analytics_data['trade_count']} trades · "
                f"Total P&amp;L: "
                f"${analytics_data['total_pnl']:,.2f} · "
                f"Win rate: {analytics_data['win_rate']:.1f}%"
            ),
            styles["Normal"],
        ),
        Spacer(1, 0.18 * inch),
    ]

    headers = [
        "Date", "Symbol", "Dir.", "Setup", "Condition",
        "Planned R:R", "Realised R:R", "Rules", "Exit", "P&L",
    ]

    data = [headers]

    for row in rows:
        data.append([
            escape(str(row["trade_date"])),
            escape(str(row["symbol"])),
            escape(str(row["direction"])),
            escape(str(row["setup"])),
            escape(str(row["market_condition"])),
            f"{row['planned_rr']:.2f}R",
            f"{row['realised_rr']:.2f}R",
            "Yes" if row["rules_followed"] else "No",
            escape(str(row["exit_reason"])),
            f"${row['pnl']:,.2f}",
        ])

    table = Table(
        data,
        repeatRows=1,
        colWidths=[
            1.05 * inch, 0.55 * inch, 0.4 * inch,
            1.0 * inch, 1.0 * inch, 0.7 * inch,
            0.75 * inch, 0.45 * inch, 0.75 * inch,
            0.7 * inch,
        ],
    )

    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#1c2a3d")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#cbd5e1")),
        ("FONTSIZE", (0, 0), (-1, -1), 7),
        ("ALIGN", (5, 1), (-1, -1), "RIGHT"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [
            colors.white,
            colors.HexColor("#f1f5f9"),
        ]),
    ]))

    story.append(table)

    if analytics_data["mistakes"]["rule_breaks"]:
        mistakes = analytics_data["mistakes"]

        story.extend([
            Spacer(1, 0.18 * inch),
            Paragraph(
                (
                    f"Rule-break summary: {mistakes['rule_breaks']} "
                    f"trades broke rules and produced "
                    f"${mistakes['rule_break_loss']:,.2f} in losses. "
                    f"Manual/breakeven exits among rule breaks: "
                    f"{mistakes['early_exit_breaks']}."
                ),
                styles["Normal"],
            ),
        ])

    doc.build(story)
    buffer.seek(0)

    return send_file(
        buffer,
        as_attachment=True,
        download_name="tradelog-journal.pdf",
        mimetype="application/pdf",
    )


